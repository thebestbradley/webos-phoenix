// The Phosphor glyphs the shell draws in Ember Glass (docs/SYSTEM-UI-2.md;
// SPEC.md: "Icons: Phosphor (MIT), only the glyphs used"), light weight, as
// path data for QML (EgIcon.qml): writes shell/qml/Phoenix/Shell/
// EmberGlassIcons.js from @phosphor-icons/core's SVGs (MIT; its licence is
// shell/design/LICENSE-phosphor, its provenance shell/design/PROVENANCE.md).
//
//   node tools/gen-ember-glass-icons.cjs --from DIR
//
// DIR: a node_modules folder holding @phosphor-icons/core (Ember Glass UI's
// checkout has one: its packages/icons build reads the same package).

"use strict";
const fs = require("fs");
const path = require("path");

const REPO = path.resolve(__dirname, "..");
const OUT = path.join(REPO, "shell/qml/Phoenix/Shell/EmberGlassIcons.js");
const WEIGHT = "light";
// Only the glyphs the shell draws.
const GLYPHS = [
    // The status bar (StatusBar.qml): the app menu tab's caret, the signal's
    // and Wi-Fi's levels, the radios.
    "caret-down",
    "cell-signal-none", "cell-signal-low", "cell-signal-medium", "cell-signal-high", "cell-signal-full", "cell-signal-slash",
    "wifi-none", "wifi-low", "wifi-medium", "wifi-high", "wifi-slash",
    "airplane", "bluetooth", "bluetooth-connected",
    // Just Type and the dock (SearchPill.qml, QuickLaunch.qml).
    "magnifying-glass", "phone", "envelope-simple", "chat-circle", "calendar-blank", "squares-four"
];

function main() {
    const args = process.argv.slice(2);
    const i = args.indexOf("--from");
    if (i < 0 || !args[i + 1]) {
        console.error("gen-ember-glass-icons: --from <node_modules with @phosphor-icons/core>");
        process.exit(2);
    }
    const pkg = path.join(path.resolve(args[i + 1]), "@phosphor-icons", "core");
    const version = JSON.parse(fs.readFileSync(path.join(pkg, "package.json"), "utf8")).version;
    const glyphs = {};
    for (const name of GLYPHS) {
        const file = path.join(pkg, "assets", WEIGHT, `${name}-${WEIGHT}.svg`);
        const svg = fs.readFileSync(file, "utf8");
        const viewBox = (/viewBox="([^"]+)"/.exec(svg) || [])[1];
        const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1]);
        if (!viewBox || paths.length === 0)
            throw new Error(file + ": no viewBox or paths");
        glyphs[name] = { viewBox: viewBox.split(/\s+/).map(Number), paths };
    }
    const out = [
        "// Generated by tools/gen-ember-glass-icons.cjs from @phosphor-icons/core " + version + " (" + WEIGHT + "): do not edit.",
        "// Phosphor Icons, MIT (shell/design/LICENSE-phosphor; shell/design/PROVENANCE.md).",
        "// Only the glyphs the shell draws in Ember Glass (docs/SYSTEM-UI-2.md); EgIcon.qml draws them.",
        ".pragma library",
        "",
        "var version = " + JSON.stringify(version) + ";",
        "var glyphs = " + JSON.stringify(glyphs, null, 1).replace(/\n\s*/g, " ") + ";",
        ""
    ].join("\n");
    fs.writeFileSync(OUT, out);
    console.log("wrote " + path.relative(REPO, OUT) + " (" + GLYPHS.length + " glyphs, Phosphor " + version + ")");
}

main();
