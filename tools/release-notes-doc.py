"""docs/RELEASE-NOTES.md, for people reading the repository, from the system's
release notes: the file product.json names (release-notes.json; the format of
docs/APP-STORE.md "Update logs"), which the system ships and Settings > Updates
shows. Edit the JSON, then run this.

  python3 tools/release-notes-doc.py            rewrite docs/RELEASE-NOTES.md
  python3 tools/release-notes-doc.py --check    fail if docs/RELEASE-NOTES.md is stale
"""

import datetime
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOC = os.path.join(ROOT, "docs", "RELEASE-NOTES.md")
KINDS = [("new", "New"), ("improved", "Improved"), ("fixed", "Fixed"), ("known", "Known issues")]


def load():
    with open(os.path.join(ROOT, "product.json"), encoding="utf-8") as f:
        product = json.load(f)
    notes_file = product["releaseNotes"]
    with open(os.path.join(ROOT, notes_file), encoding="utf-8") as f:
        notes = json.load(f)
    return product, notes_file, notes


def day(date):
    d = datetime.date.fromisoformat(date)
    return "%d %s %d" % (d.day, d.strftime("%B"), d.year)


def markdown():
    product, notes_file, notes = load()
    name = product["name"]
    out = ["<!-- Generated by tools/release-notes-doc.py from %s: edit that file, then run it. -->" % notes_file, "",
           "# %s release notes" % name, "",
           "What each version of %s brings, newest first. The system shows the same notes in Settings > Updates "
           "(\"What's New in This Version\") and Device Info. The version the system reports is product.json's "
           "(%s now); the notes' format is [APP-STORE.md, \"Update logs\"](APP-STORE.md#315-update-logs)." % (name, product["version"]),
           ""]
    for v in notes["versions"]:
        out += ["## %s %s" % (name, v["version"]), "", "*%s*" % day(v["date"]), "", v["summary"], ""]
        for key, heading in KINDS:
            if v.get(key):
                out += ["### " + heading, ""] + ["- " + item for item in v[key]] + [""]
    return "\n".join(out)


def main(argv):
    if argv == ["--check"]:
        try:
            with open(DOC, encoding="utf-8") as f:
                current = f.read()
        except OSError:
            current = None
        if current != markdown():
            print("docs/RELEASE-NOTES.md is stale: run python3 tools/release-notes-doc.py", file=sys.stderr)
            return 1
        return 0
    if argv:
        print(__doc__, file=sys.stderr)
        return 2
    with open(DOC, "w", encoding="utf-8") as f:
        f.write(markdown())
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
