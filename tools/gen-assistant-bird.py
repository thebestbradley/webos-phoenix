"""Write the Phoenix Assistant's character (docs/ASSISTANT-CHARACTER.md) for
its two renderers from its one source, art/assistant-bird/bird.json:

  shell/qml/Phoenix/Shell/AssistantBirdData.js   the shell's (AssistantBird.qml)
  apps/assistant/src/bird/birdData.ts            the Assistant app's (Bird.tsx)
  apps/assistant/src/bird/bird.generated.css     its flame, extras, breath and
                                                 acting keyframes (the app's CSP
                                                 allows no style made at run time)

Both get the parts' path data and colours, the pose, eye and beak tables
and the motion as they are in bird.json, plus what is worked out here once:
each part's bounding box (cubic and quadratic curves' extremes included),
the point each flame flickers about (its key "origin", a fraction of its
box, as CSS transform-box: fill-box would take it) and the flicker keys
padded to four (the shell's flicker plays exactly three steps each way);
each pose's acting checked (its loop starts and ends at rest), its keys
filled out to [at, rotation, x, y, scale x, scale y] and padded to six
("steps", for the shell's five-step loop), and each channel's pivot.

    python3 tools/gen-assistant-bird.py           write them
    python3 tools/gen-assistant-bird.py --check   fail if any is out of date (CI)
"""

